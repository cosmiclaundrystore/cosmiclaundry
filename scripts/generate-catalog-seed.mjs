// Writes the catalog seed migration from lib/catalog/seed-data.ts.
// Run: node scripts/generate-catalog-seed.mjs supabase/migrations/20261121085304_catalog_seed.sql
import { writeFileSync } from 'node:fs';
import { catalogSnapshot } from '../lib/catalog/seed-data.ts';

const target = process.argv[2];
if (!target) throw new Error('Pass the migration file to write.');

const q = (value) => (value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`);
const SIZES = ['S', 'M', 'L', 'XL', 'XXL'];
const COLORS = [
  { id: 'black', label: 'Black' },
  { id: 'white', label: 'White' },
];

const { collections, products } = catalogSnapshot;
const lines = [];
const rows = (table, columns, values) =>
  lines.push(`insert into public.${table} (${columns.join(', ')}) values\n  ${values.join(',\n  ')};\n`);

lines.push('-- Cosmic Laundry launch catalog: 7 Laundries, 16 tees in black and white, LK prices.');
lines.push('-- Generated by scripts/generate-catalog-seed.mjs from lib/catalog/seed-data.ts.');
lines.push('-- UK and US prices are added once they are decided (Phase 3).\n');

rows('regions', ['code', 'name', 'currency', 'is_default', 'sort_order'], [
  `('LK', 'Sri Lanka', 'LKR', true, 1)`,
  `('UK', 'United Kingdom', 'GBP', false, 2)`,
  `('US', 'United States', 'USD', false, 3)`,
]);

rows(
  'collections',
  ['id', 'name', 'short_name', 'tagline', 'description', 'featured_product_id', 'tint', 'accent', 'theme', 'sort_order'],
  collections.map((c, i) =>
    `(${[c.id, c.name, c.short, c.tagline, c.description, c.featured, c.tint, c.accent, c.theme].map(q).join(', ')}, ${(i + 1) * 10})`,
  ),
);

rows(
  'products',
  ['id', 'collection_id', 'name', 'description', 'default_color', 'sort_order'],
  products.map((p, i) => `(${[p.id, p.collection, p.name, p.description, p.defaultColor].map(q).join(', ')}, ${(i + 1) * 10})`),
);

rows(
  'product_colors',
  ['product_id', 'color', 'label', 'sort_order'],
  products.flatMap((p) => COLORS.map((c, i) => `(${q(p.id)}, ${q(c.id)}, ${q(c.label)}, ${i + 1})`)),
);

rows(
  'product_variants',
  ['product_id', 'color', 'size'],
  products.flatMap((p) => COLORS.flatMap((c) => SIZES.map((s) => `(${q(p.id)}, ${q(c.id)}, ${q(s)})`))),
);

rows(
  'product_prices',
  ['product_id', 'region_code', 'amount_minor'],
  products.filter((p) => typeof p.price === 'number').map((p) => `(${q(p.id)}, 'LK', ${Math.round(p.price * 100)})`),
);

writeFileSync(target, lines.join('\n'));
console.log(`Wrote ${target}`);
