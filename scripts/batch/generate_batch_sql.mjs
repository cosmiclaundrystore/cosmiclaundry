// Writes the SQL that adds a batch (new Laundries and tees) to Supabase.
// Usage: node scripts/batch/generate_batch_sql.mjs batches/<batch>.json > /tmp/<batch>.sql
//
// - New Laundries and tees are added after the existing ones (sort order continues from the current maximum).
// - Every tee gets black and white, sizes S–XXL (stock not tracked) and the batch price for each region listed.
// - A tee or Laundry id that already exists makes the whole thing fail, so nothing is half-added or overwritten.
// - "showOnHome": false on a new Laundry keeps its tees out of the home page hero and tee strip.
// - A product may also go into an existing Laundry: list that Laundry with "existing": true and only its products.
import { readFileSync } from 'node:fs';

const manifest = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const q = (v) => (v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const SIZES = ['S', 'M', 'L', 'XL', 'XXL'];
const MINOR_UNITS = { LK: 100, UK: 100, US: 100 };

const newCollections = manifest.collections.filter((c) => !c.existing);
const products = manifest.collections.flatMap((c) => c.products.map((p) => ({ ...p, collection: c.id })));

const out = [];
out.push(`-- Batch ${manifest.batch} (${manifest.source}): ${newCollections.length} new Laundries, ${products.length} new tees.`);
out.push('-- Generated by scripts/batch/generate_batch_sql.mjs from batches/' + manifest.batch + '.json.\n');

if (newCollections.length) {
  out.push(`insert into public.collections (id, name, short_name, tagline, description, featured_product_id, tint, accent, theme, show_on_home, sort_order)
select v.id, v.name, v.short_name, v.tagline, v.description, v.featured, v.tint, v.accent, v.theme, v.show_on_home, base.m + v.ord * 10
from (values
  ${newCollections
    .map((c, i) => `(${[c.id, c.name, c.short, c.tagline, c.description, c.featured, c.tint, c.accent, c.theme].map(q).join(', ')}, ${c.showOnHome !== false}, ${i + 1})`)
    .join(',\n  ')}
) as v (id, name, short_name, tagline, description, featured, tint, accent, theme, show_on_home, ord)
cross join (select coalesce(max(sort_order), 0) as m from public.collections) as base;
`);
}

out.push(`insert into public.products (id, collection_id, name, description, default_color, sort_order)
select v.id, v.collection_id, v.name, v.description, v.default_color, base.m + v.ord * 10
from (values
  ${products.map((p, i) => `(${[p.id, p.collection, p.name, p.description, p.defaultColor].map(q).join(', ')}, ${i + 1})`).join(',\n  ')}
) as v (id, collection_id, name, description, default_color, ord)
cross join (select coalesce(max(sort_order), 0) as m from public.products) as base;
`);

// The batch's tee ids, listed once and used by the inserts below (dropped when the transaction ends).
out.push(`create temporary table batch_products (id text primary key) on commit drop;
insert into batch_products (id) values ${products.map((p) => `(${q(p.id)})`).join(', ')};
`);

out.push(`insert into public.product_colors (product_id, color, label, sort_order)
select p.id, c.color, c.label, c.sort_order
from public.products p
cross join (values ('black', 'Black', 1), ('white', 'White', 2)) as c (color, label, sort_order)
where p.id in (select id from batch_products)
order by p.sort_order, c.sort_order;
`);

out.push(`insert into public.product_variants (product_id, color, size)
select pc.product_id, pc.color, s.size
from public.product_colors pc
join public.products p on p.id = pc.product_id
cross join (values ${SIZES.map((s, i) => `('${s}', ${i + 1})`).join(', ')}) as s (size, ord)
where pc.product_id in (select id from batch_products)
order by p.sort_order, pc.sort_order, s.ord;
`);

// Regions the manifest leaves out get the shop's standard price (3,499 LKR, £19.99, $24.99).
const DEFAULT_PRICE = { LK: 3499, UK: 19.99, US: 24.99 };
for (const [region, amount] of Object.entries({ ...DEFAULT_PRICE, ...(manifest.price ?? {}) })) {
  out.push(`insert into public.product_prices (product_id, region_code, amount_minor)
select id, ${q(region)}, ${Math.round(amount * MINOR_UNITS[region])} from public.products where id in (select id from batch_products) order by sort_order;
`);
}

process.stdout.write(out.join('\n'));
